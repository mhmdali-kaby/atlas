<?php

declare(strict_types=1);

namespace App\Support\Defaults;

use InvalidArgumentException;
use stdClass;
use Symfony\Component\Yaml\Yaml;

/**
 * Renders config/defaults.yaml into the PHP and Python defaults files (brief §21).
 *
 * Output is deterministic: the same YAML always produces byte-identical files.
 * Floats are refused so percentages and money can only be decimal strings.
 */
final class DefaultsGenerator
{
    public const HEADER = 'GENERATED by `php artisan atlas:defaults` from config/defaults.yaml — do not edit.';

    public function __construct(
        private readonly string $yamlPath,
        private readonly string $phpPath,
        private readonly string $pythonPath,
    ) {}

    public static function forRepository(): self
    {
        $root = dirname(base_path());

        return new self(
            $root.'/config/defaults.yaml',
            config_path('atlas_defaults.php'),
            $root.'/services/shared/src/atlas_shared/defaults.py',
        );
    }

    public function yamlPath(): string
    {
        return $this->yamlPath;
    }

    public function phpPath(): string
    {
        return $this->phpPath;
    }

    public function pythonPath(): string
    {
        return $this->pythonPath;
    }

    /**
     * @return array{php: string, python: string}
     */
    public function render(?string $yaml = null): array
    {
        $yaml ??= (string) file_get_contents($this->yamlPath);
        $data = Yaml::parse($yaml, Yaml::PARSE_OBJECT_FOR_MAP | Yaml::PARSE_EXCEPTION_ON_INVALID_TYPE);

        if (! $data instanceof stdClass) {
            throw new InvalidArgumentException('config/defaults.yaml must contain a mapping at the top level.');
        }

        return [
            'php' => $this->renderPhp($data),
            'python' => $this->renderPython($data),
        ];
    }

    /**
     * Files whose contents differ from what the YAML would generate.
     *
     * @return list<string>
     */
    public function staleFiles(): array
    {
        $rendered = $this->render();
        $stale = [];

        foreach ([$this->phpPath => $rendered['php'], $this->pythonPath => $rendered['python']] as $path => $expected) {
            if (! is_file($path) || file_get_contents($path) !== $expected) {
                $stale[] = $path;
            }
        }

        return $stale;
    }

    public function write(): void
    {
        $rendered = $this->render();
        file_put_contents($this->phpPath, $rendered['php']);
        file_put_contents($this->pythonPath, $rendered['python']);
    }

    private function renderPhp(stdClass $data): string
    {
        return "<?php\n\n"
            ."declare(strict_types=1);\n\n"
            .'// '.self::HEADER."\n\n"
            .'return '.$this->phpValue($data, 0, 'root').";\n";
    }

    private function renderPython(stdClass $data): string
    {
        return '# '.self::HEADER."\n"
            ."# Percentages and money are decimal strings: wrap them in decimal.Decimal before maths.\n\n"
            ."from typing import Any, Final\n\n"
            .'DEFAULTS: Final[dict[str, Any]] = '.$this->pythonValue($data, 0, 'root')."\n";
    }

    private function phpValue(mixed $value, int $depth, string $path): string
    {
        if ($value instanceof stdClass || is_array($value)) {
            $isMap = $value instanceof stdClass;
            $items = (array) $value;
            if ($items === []) {
                return '[]';
            }
            $pad = str_repeat('    ', $depth + 1);
            $lines = [];
            foreach ($items as $key => $item) {
                $prefix = $isMap ? $this->phpString((string) $key).' => ' : '';
                $lines[] = $pad.$prefix.$this->phpValue($item, $depth + 1, $path.'.'.$key).',';
            }

            return "[\n".implode("\n", $lines)."\n".str_repeat('    ', $depth).']';
        }

        return $this->scalar($value, $path, 'php');
    }

    private function pythonValue(mixed $value, int $depth, string $path): string
    {
        if ($value instanceof stdClass || is_array($value)) {
            $isMap = $value instanceof stdClass;
            $items = (array) $value;
            if ($items === []) {
                return $isMap ? '{}' : '[]';
            }
            $pad = str_repeat('    ', $depth + 1);
            $lines = [];
            foreach ($items as $key => $item) {
                $prefix = $isMap ? $this->pythonString((string) $key).': ' : '';
                $lines[] = $pad.$prefix.$this->pythonValue($item, $depth + 1, $path.'.'.$key).',';
            }
            [$open, $close] = $isMap ? ['{', '}'] : ['[', ']'];

            return $open."\n".implode("\n", $lines)."\n".str_repeat('    ', $depth).$close;
        }

        return $this->scalar($value, $path, 'python');
    }

    private function scalar(mixed $value, string $path, string $lang): string
    {
        return match (true) {
            is_string($value) => $lang === 'php' ? $this->phpString($value) : $this->pythonString($value),
            is_int($value) => (string) $value,
            is_bool($value) => $lang === 'php' ? ($value ? 'true' : 'false') : ($value ? 'True' : 'False'),
            $value === null => $lang === 'php' ? 'null' : 'None',
            is_float($value) => throw new InvalidArgumentException(
                "Float at {$path} in config/defaults.yaml; quote it as a decimal string (e.g. \"{$value}\")."
            ),
            default => throw new InvalidArgumentException("Unsupported value at {$path} in config/defaults.yaml."),
        };
    }

    private function phpString(string $value): string
    {
        return "'".str_replace(['\\', "'"], ['\\\\', "\\'"], $value)."'";
    }

    private function pythonString(string $value): string
    {
        return '"'.str_replace(['\\', '"', "\n"], ['\\\\', '\\"', '\\n'], $value).'"';
    }
}

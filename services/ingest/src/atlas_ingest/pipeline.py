"""The per-poll pipeline: canonicalise → skip if seen → extract text → detect language → enrich hook
→ insert into news_items.

Dedupe is on ``canonical_url_hash`` (sha256 of the canonical URL, generated by the DB). Seen URLs
are filtered with one indexed lookup before any article is fetched, and the insert itself is
``ON CONFLICT (canonical_url_hash) DO NOTHING``, so two sources racing on one story store it once.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime

from atlas_shared.db import NewsItem
from sqlalchemy import Engine, select
from sqlalchemy.dialects.postgresql import insert

from atlas_ingest.canonical import canonicalize_url, url_hash
from atlas_ingest.enrichment import EnrichContext, EnrichHook, enrich_items
from atlas_ingest.extract import Extractor, detect_language
from atlas_ingest.items import PreparedItem, RawItem

logger = logging.getLogger("atlas_ingest.pipeline")

EXTRACT_CONCURRENCY = 4


@dataclass(frozen=True)
class PollResult:
    fetched: int
    new: int
    inserted: int


def _seen(engine: Engine, hashes: list[bytes]) -> set[bytes]:
    if not hashes:
        return set()
    with engine.connect() as conn:
        rows = conn.execute(
            select(NewsItem.canonical_url_hash).where(NewsItem.canonical_url_hash.in_(hashes))
        )
        return {bytes(r[0]) for r in rows if r[0] is not None}


def _insert(engine: Engine, items: Sequence[PreparedItem]) -> int:
    if not items:
        return 0
    stmt = (
        insert(NewsItem)
        .values([item.row() for item in items])
        .on_conflict_do_nothing(index_elements=["canonical_url_hash"])
        .returning(NewsItem.id)
    )
    with engine.begin() as conn:
        return len(conn.execute(stmt).all())


class Pipeline:
    def __init__(
        self,
        *,
        engine: Engine,
        extractor: Extractor,
        max_extract_per_poll: int,
        enrich: EnrichHook = enrich_items,
    ) -> None:
        self.engine = engine
        self.extractor = extractor
        self.max_extract_per_poll = max_extract_per_poll
        self.enrich = enrich

    async def process(self, source_key: str, raw_items: Sequence[RawItem], now: datetime) -> PollResult:
        # 1. canonicalise, dedupe inside the batch (first occurrence wins)
        batch: dict[bytes, tuple[str, RawItem]] = {}
        for raw in raw_items:
            canonical = canonicalize_url(raw.url)
            batch.setdefault(url_hash(canonical), (canonical, raw))

        # 2. skip what is already stored
        seen = await asyncio.to_thread(_seen, self.engine, list(batch))
        fresh = [(canonical, raw) for h, (canonical, raw) in batch.items() if h not in seen]

        # 3. extract article text where the feed gave only a summary
        bodies: list[str | None] = [raw.body for _, raw in fresh]
        wanted = [i for i, (_, raw) in enumerate(fresh) if raw.body is None][: self.max_extract_per_poll]
        if wanted:
            skip_hosts: set[str] = set()
            gate = asyncio.Semaphore(EXTRACT_CONCURRENCY)

            async def one(index: int) -> None:
                async with gate:
                    bodies[index] = await self.extractor.article_text(fresh[index][1].url, skip_hosts)

            await asyncio.gather(*(one(i) for i in wanted))

        # 4. language, and the row shape
        prepared: list[PreparedItem] = []
        for (canonical, raw), body in zip(fresh, bodies, strict=True):
            text = " ".join(part for part in (raw.title, raw.summary, (body or "")[:1500]) if part)
            prepared.append(
                PreparedItem(
                    source=source_key,
                    url=raw.url,
                    canonical_url=canonical,
                    title=raw.title,
                    summary=raw.summary,
                    body=body,
                    published_at=raw.published_at or now,
                    fetched_at=now,
                    language=detect_language(text, raw.language),
                    raw=raw.raw or None,
                )
            )

        # 5. enrichment hook, then insert — unless the hook stored the items itself and said how many
        #    (the ATL-65 enricher inserts each item before clustering the next one).
        stored: int | None = None
        if prepared:
            stored = await self.enrich(prepared, EnrichContext(engine=self.engine, now=now))
        inserted = stored if stored is not None else await asyncio.to_thread(_insert, self.engine, prepared)
        return PollResult(fetched=len(raw_items), new=len(fresh), inserted=inserted)
